// Event types matching eBPF definitions
const (
	EventTypeProcessExec = 1
	EventTypeProcessExit = 2
	EventTypeSyscall     = 3
	EventTypeTCPConnect  = 4
)

var errSkipEvent = errors.New("skip event")

// Event represents a unified telemetry event
type Event struct {
	Type      string                 `json:"type"`
	Timestamp time.Time              `json:"timestamp"`
	PID       uint32                 `json:"pid"`
	UID       uint32                 `json:"uid,omitempty"`
	Comm      string                 `json:"comm,omitempty"`
	Data      map[string]interface{} `json:"data"`
}

// Collector manages eBPF program loading and event collection
type Collector struct {
	cfg         *config.Config
	spec        *ebpf.CollectionSpec
	objs        *observerObjects
	links       []link.Link
	reader      *ringbuf.Reader
	running     bool
	objectPath  string
	clockOffset int64
	mu          sync.Mutex
}

// eBPF objects (auto-generated by bpf2go, we'll define them manually for now)
type observerObjects struct {
	Programs observerPrograms
	Maps     observerMaps
}

type observerPrograms struct {
	HandleExec         *ebpf.Program `ebpf:"handle_exec"`
	HandleExit         *ebpf.Program `ebpf:"handle_exit"`
	HandleSyscallEnter *ebpf.Program `ebpf:"handle_syscall_enter"`
	HandleSyscallExit  *ebpf.Program `ebpf:"handle_syscall_exit"`
	TraceTCPConnect    *ebpf.Program `ebpf:"trace_tcp_connect"`
}

type observerMaps struct {
	Events            *ebpf.Map `ebpf:"events"`
	SyscallEntryTimes *ebpf.Map `ebpf:"syscall_entry_times"`
}

type rawProcessEvent struct {
	Type      uint32
	Pad0      uint32
	Timestamp uint64
	PID       uint32
	PPID      uint32
	UID       uint32
	GID       uint32
	Comm      [16]byte
	Filename  [256]byte
	CgroupID  uint64
}

type rawExitEvent struct {
	Type      uint32
	Pad0      uint32
	Timestamp uint64
	PID       uint32
	ExitCode  uint32
}

type rawSyscallEvent struct {
	Type        uint32
	Pad0        uint32
	Timestamp   uint64
	PID         uint32
	UID         uint32
	Comm        [16]byte
	SyscallID   uint64
	SyscallName [32]byte
	DurationNS  uint64
}

type rawTCPEvent struct {
	Type      uint32
	Pad0      uint32
	Timestamp uint64
	PID       uint32
	UID       uint32
	Comm      [16]byte
	SAddr     uint32
	DAddr     uint32
	SPort     uint16
	DPort     uint16
	Pad1      uint32
	CgroupID  uint64
}

// NewCollector creates a new eBPF collector
func NewCollector(cfg *config.Config) (*Collector, error) {
	objectPath, err := resolveBPFObjectPath(cfg)
	if err != nil {
		return nil, err
	}

	spec, err := ebpf.LoadCollectionSpec(objectPath)
	if err != nil {
		return nil, fmt.Errorf("load eBPF collection spec from %s: %w", objectPath, err)
	}

	return &Collector{
		cfg:         cfg,
		spec:        spec,
		objectPath:  objectPath,
		clockOffset: estimateClockOffset(),
	}, nil
}

// Start begins event collection
func (c *Collector) Start(events chan<- Event) error {
	c.mu.Lock()
	defer c.mu.Unlock()

	if c.running {
		return errors.New("collector already running")
	}

	if err := c.loadObjectsLocked(); err != nil {
		return err
	}

	if err := c.attachProgramsLocked(); err != nil {
		c.closeLinksLocked()
		return err
	}

	reader, err := ringbuf.NewReader(c.objs.Maps.Events)
	if err != nil {
		c.closeLinksLocked()
		return fmt.Errorf("open ring buffer reader: %w", err)
	}

	c.reader = reader
	c.running = true
	log.Printf("Collector started using eBPF object %s", c.objectPath)

	go c.readEvents(reader, events)
	return nil
}

// Stop stops event collection
func (c *Collector) Stop() {
	c.mu.Lock()
	defer c.mu.Unlock()

	if !c.running {
		return
	}

	c.running = false
	if c.reader != nil {
		c.reader.Close()
		c.reader = nil
	}
	c.closeLinksLocked()
}

// Close cleans up eBPF resources
func (c *Collector) Close() error {
	c.Stop()

	c.mu.Lock()
	defer c.mu.Unlock()

	if c.objs != nil {
		if err := c.objs.Close(); err != nil {
			return err
		}
		c.objs = nil
	}

	return nil
}

// readEvents reads from the ring buffer and parses events
func (c *Collector) readEvents(reader *ringbuf.Reader, events chan<- Event) {
	for {
		record, err := reader.Read()
		if err != nil {
			if errors.Is(err, ringbuf.ErrClosed) {
				return
			}
			log.Printf("Error reading from ring buffer: %v", err)
			continue
		}

		event, err := c.parseEvent(record.RawSample)
		if err != nil {
			if errors.Is(err, errSkipEvent) {
				continue
			}
			log.Printf("Error parsing event: %v", err)
			continue
		}

		events <- event
	}
}

func (c *Collector) loadObjectsLocked() error {
	if c.objs != nil {
		return nil
	}

	if err := rlimit.RemoveMemlock(); err != nil {
		return fmt.Errorf("remove memlock rlimit: %w", err)
	}

	spec := c.spec.Copy()
	objs := &observerObjects{}
	if err := spec.LoadAndAssign(objs, nil); err != nil {
		return fmt.Errorf("load and assign eBPF objects: %w", err)
	}

	c.objs = objs
	return nil
}

func (c *Collector) attachProgramsLocked() error {
	if c.objs == nil {
		return errors.New("eBPF objects are not loaded")
	}

	if len(c.links) != 0 {
		return errors.New("collector links already attached")
	}

	var attachErrs []error
	attach := func(name string, fn func() (link.Link, error)) {
		l, err := fn()
		if err != nil {
			attachErrs = append(attachErrs, fmt.Errorf("%s: %w", name, err))
			log.Printf("Skipping %s: %v", name, err)
			return
		}
		c.links = append(c.links, l)
		log.Printf("Attached %s", name)
	}

	if c.cfg.MonitorProcesses {
		attach("sched_process_exec tracepoint", func() (link.Link, error) {
			return link.Tracepoint("sched", "sched_process_exec", c.objs.Programs.HandleExec, nil)
		})
		attach("sched_process_exit tracepoint", func() (link.Link, error) {
			return link.Tracepoint("sched", "sched_process_exit", c.objs.Programs.HandleExit, nil)
		})
	}

	if c.cfg.MonitorSyscalls {
		attach("sys_enter raw tracepoint", func() (link.Link, error) {
			return link.AttachRawTracepoint(link.RawTracepointOptions{
				Name:    "sys_enter",
				Program: c.objs.Programs.HandleSyscallEnter,
			})
		})
		attach("sys_exit raw tracepoint", func() (link.Link, error) {
			return link.AttachRawTracepoint(link.RawTracepointOptions{
				Name:    "sys_exit",
				Program: c.objs.Programs.HandleSyscallExit,
			})
		})
	}

	if c.cfg.MonitorNetwork {
		attach("tcp_v4_connect kprobe", func() (link.Link, error) {
			return link.Kprobe("tcp_v4_connect", c.objs.Programs.TraceTCPConnect, nil)
		})
		attach("tcp_v6_connect kprobe", func() (link.Link, error) {
			return link.Kprobe("tcp_v6_connect", c.objs.Programs.TraceTCPConnect, nil)
		})
		attach("tcp_connect kprobe", func() (link.Link, error) {
			return link.Kprobe("tcp_connect", c.objs.Programs.TraceTCPConnect, nil)
		})
	}

	if len(c.links) == 0 {
		if len(attachErrs) == 0 {
			return errors.New("no collector programs were enabled")
		}
		return fmt.Errorf("no eBPF programs could be attached: %w", errors.Join(attachErrs...))
	}

	return nil
}

func (c *Collector) closeLinksLocked() {
	for _, l := range c.links {
		if l != nil {
			_ = l.Close()
		}
	}
	c.links = nil
}

func resolveBPFObjectPath(cfg *config.Config) (string, error) {
	if cfg != nil && cfg.BPFObjectPath != "" {
		if fileExists(cfg.BPFObjectPath) {
			return cfg.BPFObjectPath, nil
		}
		return "", fmt.Errorf("configured eBPF object does not exist: %s", cfg.BPFObjectPath)
	}

	candidates := []string{
		filepath.Join("ebpf", "observer.bpf.o"),
		filepath.Join("/usr/local/share", "sds-observer", "observer.bpf.o"),
	}

	if exePath, err := os.Executable(); err == nil {
		exeDir := filepath.Dir(exePath)
		candidates = append(candidates,
			filepath.Join(exeDir, "ebpf", "observer.bpf.o"),
			filepath.Join(exeDir, "..", "ebpf", "observer.bpf.o"),
			filepath.Join(exeDir, "..", "share", "sds-observer", "observer.bpf.o"),
		)
	}

	for _, candidate := range candidates {
		if fileExists(candidate) {
			return candidate, nil
		}
	}

	return "", fmt.Errorf("unable to locate observer.bpf.o; looked in %v", candidates)
}

func fileExists(path string) bool {
	info, err := os.Stat(path)
	return err == nil && !info.IsDir()
}

func (o *observerObjects) Close() error {
	var firstErr error
	closeProgram := func(program *ebpf.Program) {
		if program == nil {
			return
		}
		if err := program.Close(); err != nil && firstErr == nil {
			firstErr = err
		}
	}
	closeMap := func(m *ebpf.Map) {
		if m == nil {
			return
		}
		if err := m.Close(); err != nil && firstErr == nil {
			firstErr = err
		}
	}

	closeProgram(o.Programs.HandleExec)
	closeProgram(o.Programs.HandleExit)
	closeProgram(o.Programs.HandleSyscallEnter)
	closeProgram(o.Programs.HandleSyscallExit)
	closeProgram(o.Programs.TraceTCPConnect)
	closeMap(o.Maps.Events)
	closeMap(o.Maps.SyscallEntryTimes)

	return firstErr
}

// parseEvent parses raw bytes from eBPF into an Event
func (c *Collector) parseEvent(data []byte) (Event, error) {
	if len(data) < 4 {
		return Event{}, fmt.Errorf("data too short")
	}

	eventType := binary.LittleEndian.Uint32(data[:4])
	switch eventType {
	case EventTypeProcessExec:
		return c.parseProcessExecEvent(data)
	case EventTypeProcessExit:
		return c.parseProcessExitEvent(data)
	case EventTypeSyscall:
		return c.parseSyscallEvent(data)
	case EventTypeTCPConnect:
		return c.parseTCPConnectEvent(data)
	default:
		return Event{}, fmt.Errorf("unknown event type: %d", eventType)
	}
}

func (c *Collector) parseProcessExecEvent(data []byte) (Event, error) {
	var raw rawProcessEvent
	if err := decodeRawEvent(data, &raw); err != nil {
		return Event{}, err
	}

	return Event{
		Type:      "process.exec",
		Timestamp: c.kernelTimestampToTime(raw.Timestamp),
		PID:       raw.PID,
		UID:       raw.UID,
		Comm:      cstr(raw.Comm[:]),
		Data: map[string]interface{}{
			"ppid":      raw.PPID,
			"gid":       raw.GID,
			"filename":  cstr(raw.Filename[:]),
			"cgroup_id": raw.CgroupID,
		},
	}, nil
}

func (c *Collector) parseProcessExitEvent(data []byte) (Event, error) {
	var raw rawExitEvent
	if err := decodeRawEvent(data, &raw); err != nil {
		return Event{}, err
	}

	return Event{
		Type:      "process.exit",
		Timestamp: c.kernelTimestampToTime(raw.Timestamp),
		PID:       raw.PID,
		Data: map[string]interface{}{
			"exit_code": raw.ExitCode,
		},
	}, nil
}

func (c *Collector) parseSyscallEvent(data []byte) (Event, error) {
	var raw rawSyscallEvent
	if err := decodeRawEvent(data, &raw); err != nil {
		return Event{}, err
	}

	return Event{
		Type:      "syscall",
		Timestamp: c.kernelTimestampToTime(raw.Timestamp),
		PID:       raw.PID,
		UID:       raw.UID,
		Comm:      cstr(raw.Comm[:]),
		Data: map[string]interface{}{
			"syscall_id":   raw.SyscallID,
			"syscall_name": cstr(raw.SyscallName[:]),
			"duration_ns":  raw.DurationNS,
		},
	}, nil
}

func (c *Collector) parseTCPConnectEvent(data []byte) (Event, error) {
	var raw rawTCPEvent
	if err := decodeRawEvent(data, &raw); err != nil {
		return Event{}, err
	}

	if raw.DAddr == 0 || raw.DPort == 0 {
		return Event{}, errSkipEvent
	}

	return Event{
		Type:      "network.tcp_connect",
		Timestamp: c.kernelTimestampToTime(raw.Timestamp),
		PID:       raw.PID,
		UID:       raw.UID,
		Comm:      cstr(raw.Comm[:]),
		Data: map[string]interface{}{
			"src_addr":  ipv4ToString(raw.SAddr),
			"dst_addr":  ipv4ToString(raw.DAddr),
			"src_port":  raw.SPort,
			"dst_port":  raw.DPort,
			"cgroup_id": raw.CgroupID,
		},
	}, nil
}

// Helper functions
func decodeRawEvent(data []byte, out interface{}) error {
	if err := binary.Read(bytes.NewReader(data), binary.LittleEndian, out); err != nil {
		return fmt.Errorf("decode raw event: %w", err)
	}
	return nil
}

func estimateClockOffset() int64 {
	var mono unix.Timespec
	if err := unix.ClockGettime(unix.CLOCK_MONOTONIC, &mono); err != nil {
		return 0
	}

	monotonicNS := mono.Nano()
	if monotonicNS <= 0 {
		return 0
	}

	return time.Now().UnixNano() - monotonicNS
}

func (c *Collector) kernelTimestampToTime(timestamp uint64) time.Time {
	if timestamp == 0 || c.clockOffset == 0 {
		return time.Now().UTC()
	}

	observedAt := time.Unix(0, int64(timestamp)+c.clockOffset).UTC()
	now := time.Now().UTC()
	if observedAt.Before(time.Date(2000, 1, 1, 0, 0, 0, 0, time.UTC)) || observedAt.After(now.Add(24*time.Hour)) {
		return now
	}

	return observedAt
}

func cstr(b []byte) string {
	for i, c := range b {
		if c == 0 {
			return string(b[:i])
		}
	}
	return string(b)
}

func ipv4ToString(ip uint32) string {
	return net.IPv4(byte(ip), byte(ip>>8), byte(ip>>16), byte(ip>>24)).String()
}
